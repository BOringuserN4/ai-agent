"""
eval_rerank.py — rerank 层评估骨架（2026/09/29）

=== 技术背景（为什么需要 rerank）===

当前用的是**双塔（bi-encoder）**：查询与文档**分别编码**，然后比向量距离。
  · 优点：文档向量可**离线预计算** → 检索快
  · 致命缺陷：编码文档时**不知道谁会来查它** → 字面不像但语义相关的会漏

这正是 09-23 那个召回断层的根因：
  记忆「用户是一名测试开发工程师」（陈述句）
  问句「我的职业是什么？」（疑问句）→ 0.5051，召不回。

**交叉编码器（cross-encoder）**则把查询与文档**拼在一起送进模型**，
内部充分交互 → 准确得多。但它**无法预计算**，检索 N 条要 N 次完整推理，
复杂度差 4 个数量级（1 万条：几毫秒 vs 上百秒）。

因此业界标准是**两阶段**（retrieve-then-rerank）：
  阶段一 · 召回：双塔 + 向量库 → top-K（快、粗、宁可多带）
  阶段二 · 精排：交叉编码器逐条打分 → top-N（慢、准、只有 K 条）

=== 本次要验证的三件事 ===

  1. **K 放宽 + 精排** 能否把「原本排在 K 之外」的正确记忆救回来？
     （注意：rerank **无法**挽回阶段一没召回的 —— 这是它的硬边界）
  2. 精度是**提升**还是可能**下降**？
     （rerank 会重排，打错分时会把对的压下去 —— 必须实测，不能假设）
  3. 成本与延迟是否可接受？

用法：.venv/bin/python eval_rerank.py
"""
