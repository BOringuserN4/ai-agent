def build_corpus_store():
    """把 CORPUS 灌进一个独立的测试库。"""
    d = tempfile.mkdtemp(prefix="rerank_")
    store = MemoryStore(chroma_dir=d)
    store.clear()
    for text, qs in CORPUS:
        store.add(text, {"type": "test"},
                  embed_text=build_embed_text(text, qs))
    return store


def main():
    print("=" * 78)
    print("🧪 rerank 层评估（语料 %d 条 / 用例 %d 条）" % (len(CORPUS), len(CASES)))
    print("=" * 78)
    print("对照：仅向量（现状） vs 向量+rerank")
    print("关键指标：**K 之外的正确记忆，rerank 能否救回**\n")

    store = build_corpus_store()
    print(f"库已建好：{store.count()} 条｜后端 {store.backend.model}｜集合 {store.collection_name}\n")

    # 先看看纯向量检索的排序情况（不设阈值，看全貌）
    print("--- 阶段一：纯向量召回（min_score=0，看完整排序）---")
    for q, tgt, diff in CASES[:6]:
        r = store.search(q, top_k=len(CORPUS), min_score=0.0)
        rank = next((i for i, x in enumerate(r)
                     if CORPUS[tgt][0] == x["text"]), -1) if tgt is not None else None
        pos = f"#{rank}" if rank is not None and rank >= 0 else "未找到"
        sc = f"{r[rank]['score']:.4f}" if rank is not None and rank >= 0 else "-"
        print(f"  [{diff:<6}] {q[:18]:<20} 期望在库中排 {pos} ({sc})")
    print()

    # ============================================================
    # 正式对照：仅向量 vs 向量+rerank
    # ============================================================
    from agent.rerank import Reranker
    rr = Reranker()
    N = 3                       # 最终注入条数
    K = len(CORPUS)             # 宽召（真实场景 20~50）

    def run(use_rerank: bool):
        top1 = t3 = tot = miss = 0
        lats = []
        for q, tgt, diff in CASES:
            if tgt is None:
                continue
            tot += 1
            t0 = time.time()
            cand = store.search(q, top_k=K, min_score=0.0)
            ranked = rr.apply(q, cand) if use_rerank else cand
            lats.append(time.time() - t0)
            want = CORPUS[tgt][0]
            # 阶段一是否召回 —— rerank **救不回漏召**，所以要单独看
            if not any(x["text"] == want for x in cand):
                miss += 1
            names = [x["text"] for x in ranked[:N]]
            if names and names[0] == want:
                top1 += 1
            if want in names:
                t3 += 1
        return {"top1": top1, "t3": t3, "tot": tot, "miss": miss,
                "lat": statistics.median(lats) * 1000}

    a = run(False)
    b = run(True)
    print("=" * 78)
    print("📊 两阶段对照：召回 K=%d → 精排取 N=%d" % (K, N))
    print("=" * 78)
    print(f"{'配置':<16}{'Top-1':>8}{'Top-3':>8}{'阶段一漏召':>11}{'延迟中位':>10}")
    print("-" * 58)
    for lab, r in (("仅向量", a), ("向量+rerank", b)):
        print(f"{lab:<16}{str(r['top1']) + '/' + str(r['tot']):>8}"
              f"{str(r['t3']) + '/' + str(r['tot']):>8}{r['miss']:>11}"
              f"{str(round(r['lat'])) + 'ms':>10}")
    print("-" * 58)
    print(f"\nTop-1：{a['top1']} → {b['top1']}（{b['top1'] - a['top1']:+d}）")
    print(f"Top-3：{a['t3']} → {b['t3']}（{b['t3'] - a['t3']:+d}）")
    print(f"延迟代价：{a['lat']:.0f}ms → {b['lat']:.0f}ms（+{b['lat'] - a['lat']:.0f}ms）")

    # 找出 rerank 改坏的用例（这是最有价值的细节）
    print("\n--- rerank 改变 Top-1 的用例 ---")
    for q, tgt, diff in CASES:
        if tgt is None:
            continue
        cand = store.search(q, top_k=K, min_score=0.0)
        ranked = rr.apply(q, cand)
        want = CORPUS[tgt][0]
        if (cand[0]["text"] == want) != (ranked[0]["text"] == want):
            v, r_ = cand[0], ranked[0]
            verdict = "✅ rerank 修好" if r_["text"] == want else "❌ rerank 弄坏"
            print(f"  [{diff}] {q}")
            print(f"     向量#1 {v['score']:.4f} {v['text'][:34]}")
            print(f"     rerank#1 {r_['score']:.4f} {r_['text'][:34]}   {verdict}")

    print("\n📌 结论要点：")
    print("  · rerank **救不回阶段一漏召** —— 它的天花板在召回")
    print("  · 两种检索的失败模式**不同**：向量被词面重叠骗，rerank 被俚语/生词骗")
    print("  · 是否值得加，看**实测**：本项目当前语料下不加更好")


if __name__ == "__main__":
    main()
