def memory_cases():
    """返回记忆用例列表（便于单独跑）。"""
    return list(MEMORY_CASES)


def categorize():
    """返回 {category: [case, ...]}，便于按类别统计。"""
    out = {}
    for c in GOLDEN_SET:
        out.setdefault(c["category"], []).append(c)
    return out


