# 记忆用例集（2026/09/23 新增，收尾章）
#
# 为什么单独一个列表、而不混进 GOLDEN_SET：
#   ① 原 14 条是**无状态**的（跑完不留痕）；记忆用例要**种记忆**，
#      两者混在一起会互相干扰（记忆残留会污染无状态用例）；
#   ② 分开便于单独跑（`mcp_...` 风格），也便于对比「有记忆 vs 无记忆」。
#
# 一条记忆用例比普通用例多三样：
#   seed:        跑之前要往记忆库种什么（文本 + 元数据）
#   must_recall: 答案里**必须出现**的关键事实 —— 这是「记忆真的起作用」的判据
#   cleanup:     跑完是否清空记忆库（**必为 True**，见下）
#
# ⚠️ cleanup 为什么必须是 True（2026/09/23 实测）：
#   记忆库是**跨轮持久化**的（ChromaDB 落盘），而用例是**逐条跑**的。
#   若不清理，上一条用例种下的记忆会留在库里，被下一条的检索命中：
#     用例A 种「用户偏好 Python 写脚本」
#     用例B 种「用户偏好 Java 写后端」，B 查询 → 同时召回 A 的 0.7175 那条
#     （0.7175 > 阈值 0.6，**会被真的注入 B 的上下文**）
#   ⇒ 测的就变成「两条叠加的效果」，不是各自的效果。
#   这与 eval_memory_recall.py 用独立 chroma_data_eval/ 目录是同一个道理：
#   **评测用例之间必须隔离。**
#
# 题面设计原则（最关键）：
#   问题必须**无法被猜出来** —— 答案只存在于记忆里，模型凭空编不出。
#   ❌「什么是向量数据库？」→ 不用记忆也能答对，验证不了任何东西
#   ✅「我的猫叫什么名字？」→ 只有记忆里有「豆豆」才答得出
# ============================================================

